/** Standard demo bay layout for ParkEasy's interactive reservation preview */
export function buildDemoFloorBays(
  floor: FloorId,
  prefix: string,
  occupiedLabels: string[],
  evLabels: string[] = []
): ParkingBay[] {
  const occupiedSet = new Set(occupiedLabels);
  const evSet = new Set(evLabels);
  const bays: ParkingBay[] = [];

  for (let row = 0; row < 5; row++) {
    const leftNum = String(row * 2 + 1).padStart(2, '0');
    const rightNum = String(row * 2 + 2).padStart(2, '0');
    const leftLabel = `${prefix}-${leftNum}`;
    const rightLabel = `${prefix}-${rightNum}`;

    bays.push({
      id: `${floor}-${leftLabel}`,
      label: leftLabel,
      floor,
      side: 'left',
      rowIndex: row,
      baseOccupied: occupiedSet.has(leftLabel),
      evReady: evSet.has(leftLabel),
    });

    bays.push({
      id: `${floor}-${rightLabel}`,
      label: rightLabel,
      floor,
      side: 'right',
      rowIndex: row,
      baseOccupied: occupiedSet.has(rightLabel),
      evReady: evSet.has(rightLabel),
    });
  }

  return bays;
}

export function buildStandardDemoFloors(hasEv = false): Record<FloorId, ParkingBay[]> {
  return {
    ground: buildDemoFloorBays(
      'ground',
      'G',
      ['G-01', 'G-04', 'G-05', 'G-08', 'G-09'],
      hasEv ? ['G-02', 'G-03'] : []
    ),
    first: buildDemoFloorBays(
      'first',
      'F1',
      ['F1-01', 'F1-02', 'F1-04', 'F1-06', 'F1-08', 'F1-09'],
      hasEv ? ['F1-03', 'F1-05'] : []
    ),
    second: buildDemoFloorBays(
      'second',
      'F2',
      ['F2-01', 'F2-02', 'F2-03', 'F2-05', 'F2-06', 'F2-08', 'F2-10'],
      hasEv ? ['F2-04'] : []
    ),
  };
}

